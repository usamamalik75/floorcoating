/**
 * Every sold job carries the estimate it was sold on. The client's complaint
 * is that the crew has to ring the salesperson to find out what was actually
 * quoted, so no operations record is allowed to exist without one — these are
 * built from the systems already on the opportunity rather than hand-written.
 */
function soldEstimate(o: Opportunity, signedDaysAgo: number): Estimate {
  const short = o.id.replace('op_', '')
  const items = o.systemIds.map((pbId, i) => {
    const pb = PRICE_BOOK_BY_ID[pbId]
    const qty = pb.unit === 'lin ft' ? o.coveLf : pb.unit === 'ea' ? 1 : o.sqft
    return {
      id: `li_${short}_${i}`,
      priceBookId: pbId,
      name: pb.name,
      description: pb.description,
      qty,
      unit: pb.unit,
      unitPrice: pb.unitPrice,
    }
  })
  return {
    id: `est_${short}`,
    opportunityId: o.id,
    templateId: o.category === 'residential' ? 'pt_residential' : 'pt_standard',
    status: 'signed',
    approvedById: o.estimatorId ?? 'u_marcus',
    approvedAt: iso(signedDaysAgo - 3),
    rejectionNote: null,
    sentAt: iso(signedDaysAgo - 2),
    signedAt: iso(signedDaysAgo),
    signedBy: ACCOUNT_BY_ID[o.accountId]?.contactName ?? 'Customer',
    token: short.slice(0, 6),
    depositPct: o.category === 'residential' ? 25 : 40,
    internalNotes: '',
    options: [
      {
        id: `eo_${short}`,
        label: o.name.split('—').pop()?.trim() ?? 'Scope of work',
        kind: 'area',
        recommended: true,
        selectedByCustomer: true,
        lineItems: items,
      },
    ],
  }
}

const SOLD: Estimate[] = OPPORTUNITIES.filter(
  (o) => STAGE_BY_ID[o.stage].phase === 'operations' && !ESTIMATES.some((e) => e.opportunityId === o.id),
).map((o, i) => {
  const estimate = soldEstimate(o, -30 - i * 4)
  // The signed estimate is the contract, so the record's value follows it
  // rather than the two drifting apart across the board and the ledger.
  o.value = estimate.options
    .flatMap((opt) => opt.lineItems)
    .reduce((sum, li) => sum + li.qty * li.unitPrice, 0)
  return estimate
})

ESTIMATES.push(...SOLD)

