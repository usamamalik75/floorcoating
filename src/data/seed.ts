const DAY_MS = 86_400_000

export const iso = (offsetDays: number, hour = 9): string => {
  const d = new Date(TODAY.getTime() + offsetDays * DAY_MS)
  d.setHours(hour, 0, 0, 0)
  return d.toISOString()
}

