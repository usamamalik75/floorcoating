function line(priceBookId: string, qty: number): MaterialLine {
  const d = deriveMaterial(priceBookId, qty)!
  return {
    id: `ml_${++mlSeq}`,
    priceBookId,
    product: d.product,
    qty: d.qty,
    unit: d.unit,
    derivation: d.derivation,
    adjusted: false,
  }
}

